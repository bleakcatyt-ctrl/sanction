#!/usr/bin/env node
'use strict';

/**
 * npm run loader:config            — embed PUBLIC_URL + server identity key
 * npm run loader:config -- https://example.com
 *
 * Writes loader/Sanction.Loader/Core/BuildConfig.g.cs so a published loader
 *   • talks to the right API without a sanction.json next to the exe, and
 *   • carries the server identity public key, which makes every license token
 *     verifiable offline and makes a proxy/patched server detectable.
 *
 * Re-run this after regenerating data/server-identity.pem and rebuild the exe.
 */

const fs = require('node:fs');
const path = require('node:path');

const config = require('../server/config');
const proto = require('../server/lib/protocol');

const TARGET = path.join(config.root, 'loader', 'Sanction.Loader', 'Core', 'BuildConfig.g.cs');

const arg = process.argv[2];
const apiBase = String(arg || process.env.LOADER_API || config.publicUrl).replace(/\/+$/, '');
if (!/^https?:\/\//i.test(apiBase)) {
  console.error('Некорректный адрес API: ' + apiBase);
  process.exit(1);
}

const channel = (process.env.LOADER_CHANNEL || 'stable').toLowerCase();
if (!['stable', 'beta'].includes(channel)) {
  console.error('Канал должен быть stable или beta, получено: ' + channel);
  process.exit(1);
}

let pem;
try {
  pem = proto.identityPublicKeyPem().trim();
} catch (err) {
  console.error('Не удалось прочитать публичный ключ сервера: ' + err.message);
  process.exit(1);
}

if (!pem.includes('BEGIN PUBLIC KEY')) {
  console.error('data/server-identity.pub.pem не похож на SPKI PEM.');
  process.exit(1);
}

const fingerprint = proto.identityFingerprint();
const insecure = apiBase.startsWith('http://');

const source = `namespace Sanction.Loader.Core;

/// <summary>
/// Generated by tools/embed-loader-config.js — do not edit by hand.
/// Regenerate:  npm run loader:config [https://api.example.com]
///
///   api base   ${apiBase}
///   key id     ${fingerprint}
///   channel    ${channel}
///   embedded   ${new Date().toISOString()}
/// </summary>
internal static class BuildConfig
{
    /// <summary>Base URL of the Sanction API, no trailing slash.</summary>
    public const string ApiBase = "${apiBase}";

    /// <summary>PEM (SPKI) of the server identity key — ECDSA P-256, id ${fingerprint}.</summary>
    public const string ServerPublicKeyPem = @"${pem}";

    /// <summary>Release channel reported to the server: stable | beta.</summary>
    public const string Channel = "${channel}";

    /// <summary>UTC timestamp of the configuration embed, for support requests.</summary>
    public const string ConfiguredAt = "${new Date().toISOString()}";
}
`;

fs.mkdirSync(path.dirname(TARGET), { recursive: true });
fs.writeFileSync(TARGET, source, 'utf8');

console.log('');
console.log('Конфигурация лоадера записана');
console.log('  файл        ' + path.relative(config.root, TARGET));
console.log('  api         ' + apiBase + (insecure ? '   (НЕ защищённый канал — только для локальных тестов)' : ''));
console.log('  ключ сервера ' + fingerprint + ' (ECDSA P-256, SPKI)');
console.log('  канал       ' + channel);
console.log('');
console.log('Дальше: cd loader && ./build.sh   (или build.cmd на Windows)');
console.log('');
